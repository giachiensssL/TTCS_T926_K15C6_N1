CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_code VARCHAR(255) NOT NULL UNIQUE,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(255) NOT NULL,
    gender VARCHAR(255),
    date_of_birth DATE,
    address VARCHAR(255),
    entry_level VARCHAR(255),
    note VARCHAR(1000),
    status VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS student_class_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    class_code VARCHAR(255) NOT NULL,
    class_name VARCHAR(255) NOT NULL,
    teacher_name VARCHAR(255),
    schedule VARCHAR(255),
    room VARCHAR(255),
    start_date DATE,
    end_date DATE,
    status VARCHAR(255) NOT NULL,
    final_grade DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS student_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    operation_type VARCHAR(20) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    effective_date DATE NOT NULL,
    source_enrollment_id BIGINT REFERENCES student_class_enrollments(id),
    target_enrollment_id BIGINT REFERENCES student_class_enrollments(id),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_student_operations_student_effective
    ON student_operations(student_id, effective_date);
